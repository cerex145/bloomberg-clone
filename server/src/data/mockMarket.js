// Generar datos OHLCV realistas usando movimiento browniano geométrico
function generateOHLCVData(startPrice, days = 252) {
    const data = [];
    let price = startPrice;
    const drift = 0.0005; // 0.05% drift diario
    const volatility = 0.015; // 1.5% volatilidad diaria

    for (let i = days; i > 0; i--) {
        const randomNormal1 = Math.sqrt(-2 * Math.log(Math.random())) * Math.cos(2 * Math.PI * Math.random());
        const randomNormal2 = Math.sqrt(-2 * Math.log(Math.random())) * Math.cos(2 * Math.PI * Math.random());

        const open = price;
        const change1 = price * (drift + volatility * randomNormal1);
        const intraday = randomNormal2 * volatility * 0.5;

        const high = Math.max(open, open + change1 + Math.abs(intraday * price));
        const low = Math.min(open, open + change1 - Math.abs(intraday * price));
        const close = open + change1;

        const volume = Math.floor(Math.random() * 100000000 + 50000000);

        const date = new Date();
        date.setDate(date.getDate() - i);

        data.push({
            date: date.toISOString().split('T')[0],
            timestamp: date.getTime(),
            open: Math.round(open * 100) / 100,
            high: Math.round(high * 100) / 100,
            low: Math.round(low * 100) / 100,
            close: Math.round(close * 100) / 100,
            volume: volume
        });

        price = close;
    }

    return data;
}

